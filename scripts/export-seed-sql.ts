// Writes db/seed.sql (vehicle makes/models) for import through phpMyAdmin, after db/schema.sql.
// Usage: npm run db:seed-sql
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { vehicleCatalog } from "../src/lib/vehicles";

const esc = (value: string) => `'${value.replace(/\\/g, "\\\\").replace(/'/g, "''")}'`;

const lines = ["-- Generated by scripts/export-seed-sql.ts. Import after db/schema.sql.", "SET NAMES utf8mb4;", ""];

Object.entries(vehicleCatalog).forEach(([make, models], makeIndex) => {
  lines.push(
    `INSERT INTO vehicle_makes (name, sort_order) VALUES (${esc(make)}, ${makeIndex + 1}) ON DUPLICATE KEY UPDATE sort_order = VALUES(sort_order);`,
  );
  const values = models
    .map((model, i) => `((SELECT id FROM vehicle_makes WHERE name = ${esc(make)}), ${esc(model)}, ${i + 1})`)
    .join(",\n  ");
  if (values) {
    lines.push(
      `INSERT INTO vehicle_models (make_id, name, sort_order) VALUES\n  ${values}\nON DUPLICATE KEY UPDATE sort_order = VALUES(sort_order);`,
    );
  }
  lines.push("");
});

const target = path.join(process.cwd(), "db", "seed.sql");
writeFile(target, lines.join("\n"), "utf8").then(() => console.log(`Wrote ${target}`));
